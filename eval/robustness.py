"""Robustness of the trained agents: out-of-distribution patients and scorer noise.

  uv run python -m eval.robustness --config configs/robustness.yaml

OOD: the full-evaluation protocol on cohorts whose parameters lie outside the training ranges.
Noise: the observed outcome is flipped with probability 0.05 / 0.10 (evaluation only; the patient's
true response, learning and metrics are unaffected). The noise uses its own random stream, so the
same patients with the same luck are compared across noise levels and the change is a paired
difference. Writes results/robustness.csv and results/robustness.md.
"""
from __future__ import annotations

import argparse
import csv

import numpy as np

from core.config import load_yaml, resolve
from eval.compare import bootstrap_ci, evaluate


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/robustness.yaml")
    ap.add_argument("--n-patients", type=int, default=None)
    args = ap.parse_args()
    cfg = load_yaml(args.config)
    if args.n_patients:
        cfg["n_patients"] = args.n_patients
    rng = np.random.default_rng(cfg["seed"])
    B, labels = cfg["bootstrap_samples"], {p["key"]: p["label"] for p in cfg["policies"]}
    base = {k: cfg[k] for k in ("seed", "n_patients", "metrics", "oracle", "policies", "dropout")}
    rows = []

    ood = evaluate({**base, "cohorts": cfg["ood_cohorts"]})
    for (cohort, key), pts in ood["per_patient"].items():
        for m in cfg["metrics"]:
            mean, lo, hi = bootstrap_ci(np.array([p[m] for p in pts]), B, rng)
            rows.append({"test": "ood", "setting": cohort, "cohort": cohort, "policy": key, "metric": m,
                         "mean": mean, "ci_low": lo, "ci_high": hi, "kind": "value"})
    print("OOD done", flush=True)

    by_noise = {}
    for noise in cfg["noise_levels"]:
        by_noise[noise] = evaluate({**base, "cohorts": cfg["noise_cohorts"], "obs_noise": noise})
        print(f"noise {noise} done", flush=True)
    for noise, ev in by_noise.items():
        for (cohort, key), pts in ev["per_patient"].items():
            ref = by_noise[0.0]["per_patient"][(cohort, key)]
            for m in cfg["metrics"]:
                v = np.array([p[m] for p in pts])
                mean, lo, hi = bootstrap_ci(v, B, rng)
                rows.append({"test": "noise", "setting": f"{noise:g}", "cohort": cohort, "policy": key, "metric": m,
                             "mean": mean, "ci_low": lo, "ci_high": hi, "kind": "value"})
                if noise:
                    d = v - np.array([p[m] for p in ref])
                    dm, dlo, dhi = bootstrap_ci(d, B, rng)
                    rows.append({"test": "noise", "setting": f"{noise:g}", "cohort": cohort, "policy": key, "metric": m,
                                 "mean": dm, "ci_low": dlo, "ci_high": dhi, "kind": "paired_change_vs_0"})
    out = resolve(cfg["output_dir"])
    with open(out / "robustness.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    write_markdown(rows, cfg, labels, out / "robustness.md")
    print(f"wrote {out}/robustness.csv and robustness.md")


def write_markdown(rows, cfg, labels, path) -> None:
    cols = [("time_in_band", "in band", 1, 2), ("control_error", "\\|p-0.85\\|", 1, 3), ("learning_gain", "gain x100", 100, 2),
            ("probe_lift", "probe lift x100", 100, 2), ("quit", "quit", 1, 2)]
    get = {(r["test"], r["setting"], r["cohort"], r["policy"], r["metric"], r["kind"]): r for r in rows}
    fmt = lambda r, sc, nd, sign="": (f"{sc * r['mean']:{sign}.{nd}f} [{sc * r['ci_low']:{sign}.{nd}f}, "
                                      f"{sc * r['ci_high']:{sign}.{nd}f}]")
    lines = ["<!-- Generated by: uv run python -m eval.robustness --config configs/robustness.yaml. Do not edit by hand. -->",
             f"{cfg['n_patients']} patients per cohort; mean [95% bootstrap CI].", "",
             "**Out-of-distribution patients** (parameters outside the training ranges)", "",
             "| cohort | policy | " + " | ".join(h for _, h, _, _ in cols) + " |", "|" + "---|" * (len(cols) + 2)]
    for cohort in cfg["ood_cohorts"]:
        for p in cfg["policies"]:
            lines.append(f"| {cohort} | {labels[p['key']]} | " + " | ".join(
                fmt(get[("ood", cohort, cohort, p["key"], m, "value")], sc, nd) for m, _, sc, nd in cols) + " |")
    lines += ["", "**Scorer noise**: paired change versus no noise (same patients), mean [95% CI]", "",
              "| cohort | policy | noise | " + " | ".join(h for _, h, _, _ in cols) + " |", "|" + "---|" * (len(cols) + 3)]
    for cohort in cfg["noise_cohorts"]:
        for p in cfg["policies"]:
            for noise in cfg["noise_levels"][1:]:
                lines.append(f"| {cohort} | {labels[p['key']]} | {noise:g} | " + " | ".join(
                    fmt(get[("noise", f"{noise:g}", cohort, p["key"], m, "paired_change_vs_0")], sc, nd, "+")
                    for m, _, sc, nd in cols) + " |")
    path.write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
