"""Ablations on the full-evaluation protocol: learning-peak location, dropout, reward variants.

  uv run python -m eval.ablations --config configs/ablations.yaml

Writes results/ablations.csv, results/ablations.md and results/ablation_learning_peak.png.
"""
from __future__ import annotations

import argparse
import csv
import time

import numpy as np

from core.config import load_yaml, resolve
from eval.compare import bootstrap_ci, evaluate


def summarise(ev: dict, cfg: dict, ablation: str, setting: str, labels: dict, rng) -> list[dict]:
    rows = []
    for (cohort, key), pts in ev["per_patient"].items():
        for m in cfg["metrics"]:
            mean, lo, hi = bootstrap_ci(np.array([p[m] for p in pts]), cfg["bootstrap_samples"], rng)
            rows.append({"ablation": ablation, "setting": setting, "cohort": cohort, "policy": key,
                         "label": labels[key], "metric": m, "mean": mean, "ci_low": lo, "ci_high": hi})
    return rows


def run(cfg: dict) -> list[dict]:
    rng = np.random.default_rng(cfg["seed"])
    base = {k: cfg[k] for k in ("seed", "n_patients", "cohorts", "bootstrap_samples", "metrics", "oracle")}
    rows: list[dict] = []

    lp = cfg["learning_peak"]
    for peak in lp["peaks"]:
        pols = list(cfg["base_policies"])
        for mt in lp["matched"]:
            tag = mt["tag_085"] if peak == 0.85 else f"peak{peak:g}_"
            models = [mt["models"].format(tag=tag, seed=s) for s in cfg["seeds"]]
            if all(resolve(m).exists() for m in models):
                pols.append({"key": mt["key"], "label": mt["label"], "type": "ppo", "models": models})
        c = {**base, "policies": pols, "dropout": True, "learning_peak": peak}
        t0 = time.time()
        rows += summarise(evaluate(c), c, "learning_peak", f"{peak:g}", {p["key"]: p["label"] for p in pols}, rng)
        print(f"learning peak {peak}: {time.time() - t0:.0f}s", flush=True)

    for dropout in cfg["dropout"]:
        c = {**base, "policies": cfg["base_policies"], "dropout": dropout}
        rows += summarise(evaluate(c), c, "dropout", "on" if dropout else "off",
                          {p["key"]: p["label"] for p in cfg["base_policies"]}, rng)
        print(f"dropout {dropout} done", flush=True)

    pols = []
    for v in cfg["reward_variants"]:
        models = [v["models"].format(seed=s) for s in cfg["seeds"]]
        if all(resolve(m).exists() for m in models):
            pols.append({"key": f"ppo_{v['key']}", "label": f"PPO, {v['label']}", "type": "ppo", "models": models})
    if pols:
        c = {**base, "policies": pols, "dropout": True}
        rows += summarise(evaluate(c), c, "reward_variant", "dropout on", {p["key"]: p["label"] for p in pols}, rng)
        print("reward variants done", flush=True)
    return rows


def write_markdown(rows: list[dict], cfg: dict, path) -> None:
    cols = [("time_in_band", "in band", 1, 2), ("control_error", "\\|p-0.85\\|", 1, 3), ("learning_gain", "gain x100", 100, 2),
            ("probe_lift", "probe lift x100", 100, 2), ("quit", "quit", 1, 2)]
    get = {(r["ablation"], r["setting"], r["cohort"], r["policy"], r["metric"]): r for r in rows}
    lines = ["<!-- Generated by: uv run python -m eval.ablations --config configs/ablations.yaml. Do not edit by hand. -->",
             f"{cfg['n_patients']} held-out test patients per cohort; mean [95% bootstrap CI].", ""]
    for ablation in ("learning_peak", "dropout", "reward_variant"):
        settings = list(dict.fromkeys(r["setting"] for r in rows if r["ablation"] == ablation))
        for setting in settings:
            lines += [f"**{ablation.replace('_', ' ')} = {setting}**", "",
                      "| cohort | policy | " + " | ".join(h for _, h, _, _ in cols) + " |", "|" + "---|" * (len(cols) + 2)]
            pols = list(dict.fromkeys((r["policy"], r["label"]) for r in rows if r["ablation"] == ablation and r["setting"] == setting))
            for cohort in cfg["cohorts"]:
                for key, label in pols:
                    cells = []
                    for m, _, sc, nd in cols:
                        r = get[(ablation, setting, cohort, key, m)]
                        cells.append(f"{sc * r['mean']:.{nd}f} [{sc * r['ci_low']:.{nd}f}, {sc * r['ci_high']:.{nd}f}]")
                    lines.append(f"| {cohort} | {label} | " + " | ".join(cells) + " |")
            lines.append("")
    path.write_text("\n".join(lines) + "\n")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/ablations.yaml")
    ap.add_argument("--n-patients", type=int, default=None)
    args = ap.parse_args()
    cfg = load_yaml(args.config)
    if args.n_patients:
        cfg["n_patients"] = args.n_patients
    out = resolve(cfg["output_dir"])
    rows = run(cfg)
    with open(out / "ablations.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)
    write_markdown(rows, cfg, out / "ablations.md")
    from eval.plots import plot_learning_peak_ablation
    plot_learning_peak_ablation(rows, cfg, out / "ablation_learning_peak.png")
    print(f"wrote {out}/ablations.csv, ablations.md, ablation_learning_peak.png")


if __name__ == "__main__":
    main()
