"""Paired evaluation of therapy policies on held-out engine patients.

  uv run python -m neurocue.evaluate [--n 100] [--ppo models/engine_ppo_seed0.zip ...] [--cohort population]

Every policy treats the same test patients (same seeds), so differences are paired. Outcome: mean
unaided retention of the practised words at each test day, its gain over the pre-course value, and
the share of trials cued. Writes results/engine_trainer.md and results/engine_trainer.csv.
"""
from __future__ import annotations

import argparse
import csv
import time
from pathlib import Path

import numpy as np

from neurocue.baselines import BASELINES, RulePolicy
from neurocue.env import ACTIONS, EngineTherapyEnv, load_engine_env_config

ROOT = Path(__file__).resolve().parents[1]


class PPOWrapper:
    def __init__(self, path: str, name: str) -> None:
        from sb3_contrib import MaskablePPO
        self.model = MaskablePPO.load(path, device="cpu")
        self.name = name

    def act_vec(self, obs_vec: np.ndarray, mask: np.ndarray) -> int:
        a, _ = self.model.predict(obs_vec, action_masks=mask, deterministic=True)
        return int(a)


def run_course(env: EngineTherapyEnv, policy, k: int, rng: np.random.Generator) -> dict:
    obs, info = env.reset(options={"patient_index": k})
    done = False
    while not done:
        mask = env.action_masks()
        if isinstance(policy, RulePolicy):
            a = policy.act(env.observable(), mask, rng)
        else:
            a = policy.act_vec(obs, mask)
        obs, _, done, _, info = env.step(a)
    hist = info["history"]
    out = {"patient": k, "aq": env.tp.snapshot.aq, "cued_share": float(np.mean([h["cue"] is not None for h in hist])),
           "accuracy_in_practice": float(np.mean([h["correct"] for h in hist]))}
    for d in env.cfg.test_days:
        out[f"retention_{int(d)}"] = info["retention"][d]
        out[f"gain_{int(d)}"] = info["gain"][d]
        out[f"start_{int(d)}"] = info["start_retention"][d]
    return out


def bootstrap(v: np.ndarray, B: int, rng: np.random.Generator) -> tuple[float, float, float]:
    m = v[rng.integers(0, len(v), size=(B, len(v)))].mean(axis=1)
    return float(v.mean()), float(np.percentile(m, 2.5)), float(np.percentile(m, 97.5))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--n", type=int, default=100)
    ap.add_argument("--ppo", nargs="*", default=[])
    ap.add_argument("--cohort", default=None)
    ap.add_argument("--split", default="test")
    ap.add_argument("--baselines", nargs="*", default=list(BASELINES))
    ap.add_argument("--out", default="engine_trainer")
    args = ap.parse_args()
    cfg = load_engine_env_config()
    if args.cohort:
        cfg.cohort = args.cohort
    env = EngineTherapyEnv(cfg, split=args.split, root_seed=0)
    policies: list = [BASELINES[b]() for b in args.baselines]
    for i, p in enumerate(args.ppo):
        policies.append(PPOWrapper(p, f"ppo_{Path(p).stem}"))
    rows: dict[str, list[dict]] = {}
    for pol in policies:
        t0 = time.time()
        rng = np.random.default_rng(123)
        rows[pol.name] = [run_course(env, pol, k, rng) for k in range(args.n)]
        print(f"  {pol.name:20s} {args.n} patients in {time.time() - t0:.0f}s  retention+7 "
              f"{np.mean([r[f'retention_{int(cfg.test_days[0])}'] for r in rows[pol.name]]):.3f}", flush=True)
    d0, d1 = int(cfg.test_days[0]), int(cfg.test_days[1])
    rng = np.random.default_rng(0)
    ref = "spaced_hierarchy" if "spaced_hierarchy" in rows else list(rows)[0]
    lines = ["<!-- Generated by: uv run python -m neurocue.evaluate. Do not edit by hand. -->",
             "# Therapy policies on engine patients\n",
             f"{args.n} held-out `{args.split}` patients, cohort `{cfg.cohort}`, {len(cfg.schedule_days)} sessions of "
             f"{cfg.trials_per_session} trials on days {list(cfg.schedule_days)}, {cfg.n_items} personally hard words each "
             f"(unaided P(correct) in {list(cfg.baseline_range)} before the course). Every policy treats the same patients. "
             f"Retention = mean predicted unaided P(correct) of the practised words on the test day; gain = retention minus "
             f"the pre-course value. 95% percentile bootstrap over patients; paired differences against `{ref}`.\n",
             f"| policy | retention day {d0} | gain day {d0} | retention day {d1} | gain day {d1} | paired gain diff day {d0} vs {ref} | cued share | accuracy in practice |",
             "|---|---|---|---|---|---|---|---|"]
    csv_rows = []
    for name, rs in rows.items():
        g0 = np.array([r[f"gain_{d0}"] for r in rs]); g1 = np.array([r[f"gain_{d1}"] for r in rs])
        r0 = np.array([r[f"retention_{d0}"] for r in rs]); r1 = np.array([r[f"retention_{d1}"] for r in rs])
        m0, lo0, hi0 = bootstrap(g0, 2000, rng); m1, lo1, hi1 = bootstrap(g1, 2000, rng)
        diff = g0 - np.array([r[f"gain_{d0}"] for r in rows[ref]])
        dm, dlo, dhi = bootstrap(diff, 2000, rng)
        cs = float(np.mean([r["cued_share"] for r in rs])); acc = float(np.mean([r["accuracy_in_practice"] for r in rs]))
        lines.append(f"| {name} | {r0.mean():.3f} | {m0:+.3f} [{lo0:+.3f}, {hi0:+.3f}] | {r1.mean():.3f} | {m1:+.3f} [{lo1:+.3f}, {hi1:+.3f}] | "
                     f"{dm:+.3f} [{dlo:+.3f}, {dhi:+.3f}] | {cs:.2f} | {acc:.2f} |")
        csv_rows.append({"policy": name, f"retention_{d0}": r0.mean(), f"gain_{d0}": m0, f"gain_{d0}_lo": lo0, f"gain_{d0}_hi": hi0,
                         f"retention_{d1}": r1.mean(), f"gain_{d1}": m1, "cued_share": cs, "accuracy_in_practice": acc})
    start = np.mean([r[f"start_{d0}"] for r in rows[ref]])
    lines.append(f"\nPre-course retention of the chosen words: {start:.3f} (they were chosen to be hard). Reading: the engine's "
                 "learning layer was fitted to retrieval-practice data, so spaced retrieval beating massed and errorless "
                 "beating nothing are built in; what is not built in is how a policy trades cue-assisted success now "
                 "against weaker traces, across words of different strength, over four sessions.")
    out_md = ROOT / "results" / f"{args.out}.md"; out_md.write_text("\n".join(lines) + "\n")
    with open(ROOT / "results" / f"{args.out}.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(csv_rows[0])); w.writeheader(); w.writerows(csv_rows)
    print("\n".join(lines)); print(f"\n-> {out_md}")


if __name__ == "__main__":
    main()
