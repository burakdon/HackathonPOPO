"""Fit the population prior on the semantic/phonological lesion split to real PSST error mixes.

The engine's sampler picks (s, p) cells of the SP model that match a severity-derived accuracy,
weighted by a lognormal prior on p/s. The prior's first value came from Dell's fitted Philadelphia
patients (log p/s mean 0.5, sd 0.6). Here it is fitted instead to the error-type mix of the 74
PSST *training-split* participants on the Boston Naming Test, coded by clinician > learned coder >
rules (scripts/validate_engine.real_bnt_mix). The 33 validation/test participants are untouched, so
table 2c of the validation stays a held-out test of the result.

Method: for each (mean, sd) on a grid, sample a cohort with the training participants' AQs (20
replicates each), read each patient's expected response-type probabilities from the fitted SP grid,
pool the five error types, and score the real error counts by multinomial negative log-likelihood.
Expected probabilities ignore item difficulty and realizer fallbacks; the full simulation in
validate_engine is the check on that shortcut.

Run: uv run python -m scripts.fit_population_prior
"""
from __future__ import annotations

import collections
from pathlib import Path

import numpy as np

from patientmodel.dell_sp import NAMING_CATEGORIES, DellSPModel, load_dell_sp_config
from patientmodel.fit import load_or_build_grid
from patientmodel.population import PopulationConfig, PopulationSampler
from scripts.validate_engine import HELD_OUT, error_shares, load_psst, real_bnt_mix

ROOT = Path(__file__).resolve().parents[1]
REPORT = ROOT / "results" / "population_prior_fit.md"
ERR = ["semantic", "formal", "mixed", "unrelated", "nonword"]
MEANS = np.round(np.arange(-1.5, 1.01, 0.1), 2)
SDS = [0.3, 0.5, 0.7, 1.0]
REPS = 20


def synthetic_shares(sampler: PopulationSampler, aq: np.ndarray, seed: int) -> np.ndarray:
    pats = sampler.sample(len(aq), seed=seed, aq=aq)
    probs = np.array([[p.expected_naming[c] for c in ERR] for p in pats])
    pooled = probs.mean(axis=0)
    return pooled / pooled.sum()


def nll(counts: np.ndarray, shares: np.ndarray) -> float:
    return float(-(counts * np.log(np.clip(shares, 1e-6, None))).sum())


def main() -> None:
    cfg, fit_cfg = load_dell_sp_config()
    table = load_or_build_grid(DellSPModel(cfg), fit_cfg["grid_step"], fit_cfg["trials_per_cell"], fit_cfg["seed"])
    rows = load_psst()
    train_aq = np.array(sorted({(r["session"], float(r["aq_index"])) for r in rows if r["test"] == "BNT" and r["split"] == "train"}))[:, 1].astype(float)
    held_aq = np.array(sorted({(r["session"], float(r["aq_index"])) for r in rows if r["test"] == "BNT" and r["split"] in HELD_OUT}))[:, 1].astype(float)
    train_mix, n_final_tr, _ = real_bnt_mix(frozenset({"train"}))
    held_mix, _, _ = real_bnt_mix(HELD_OUT)
    tr_counts_c, tr_n = error_shares(train_mix)
    he_counts_c, he_n = error_shares(held_mix)
    tr_counts = np.array([tr_counts_c[k] for k in ERR], dtype=float)
    he_counts = np.array([he_counts_c[k] for k in ERR], dtype=float)
    aq_tr = np.repeat(train_aq, REPS)
    aq_he = np.repeat(held_aq, REPS)

    results = []
    for sd in SDS:
        for m in MEANS:
            sampler = PopulationSampler(table, PopulationConfig(log_ps_ratio_mean=float(m), log_ps_ratio_sd=sd))
            sh = synthetic_shares(sampler, aq_tr, seed=7)
            results.append((nll(tr_counts, sh), float(m), sd, sh))
    results.sort(key=lambda t: t[0])
    best_nll, best_m, best_sd, best_sh = results[0]
    # Saturated (real shares) and Dell-prior references
    sat = nll(tr_counts, tr_counts / tr_counts.sum())
    dell = PopulationConfig.dell_philadelphia()
    dell_sh = synthetic_shares(PopulationSampler(table, dell), aq_tr, seed=7)
    dell_nll = nll(tr_counts, dell_sh)
    # Held-out check at the chosen prior
    held_sh = synthetic_shares(PopulationSampler(table, PopulationConfig(log_ps_ratio_mean=best_m, log_ps_ratio_sd=best_sd)), aq_he, seed=11)
    held_dell = synthetic_shares(PopulationSampler(table, dell), aq_he, seed=11)
    # Profile over means at the best sd, for the report
    prof = sorted([(m, v) for v, m, sd, _ in results if sd == best_sd])
    prof_sd = sorted([(sd, v) for v, m, sd, _ in results if m == best_m])

    fmt = lambda sh: " | ".join(f"{x:.2f}" for x in sh)
    lines = ["<!-- Generated by: uv run python -m scripts.fit_population_prior. Do not edit by hand. -->",
             "# Population prior on the lesion split, fitted to PSST\n",
             f"Fitted on the {len(train_aq)} training-split participants' BNT errors ({int(tr_n)} codable, {n_final_tr} of their rows "
             f"clinician-adjudicated), by multinomial likelihood of the five SP error types under the cohort's pooled expected "
             f"response probabilities. Grid: log p/s mean {MEANS[0]} to {MEANS[-1]} by 0.1, sd in {SDS}.\n",
             f"**Chosen: log p/s mean {best_m:+.1f}, sd {best_sd}.** Deviance against the saturated model {2 * (best_nll - sat):.1f} "
             f"on 4 degrees of freedom; Dell's prior (mean {dell.log_ps_ratio_mean:+.1f}, sd {dell.log_ps_ratio_sd}) sits at "
             f"{2 * (dell_nll - sat):.1f}.\n",
             "| training participants | n | " + " | ".join(ERR) + " |", "|---|---|" + "---|" * len(ERR),
             f"| real | {int(tr_n)} | {fmt(tr_counts / tr_counts.sum())} |",
             f"| synthetic, fitted prior | | {fmt(best_sh)} |",
             f"| synthetic, Dell prior | | {fmt(dell_sh)} |",
             "\n| held-out participants | n | " + " | ".join(ERR) + " |", "|---|---|" + "---|" * len(ERR),
             f"| real | {int(he_n)} | {fmt(he_counts / he_counts.sum())} |",
             f"| synthetic, fitted prior | | {fmt(held_sh)} |",
             f"| synthetic, Dell prior | | {fmt(held_dell)} |",
             f"\n**Deviance profile over the mean at sd {best_sd}** (lower is better)\n", "| log p/s mean | deviance |", "|---|---|",
             *[f"| {m:+.1f} | {2 * (v - sat):.1f} |" for m, v in prof],
             f"\n**Deviance profile over the sd at mean {best_m:+.1f}**\n", "| log p/s sd | deviance |", "|---|---|",
             *[f"| {sd} | {2 * (v - sat):.1f} |" for sd, v in prof_sd],
             "\nThe pooled mix identifies the mean well and the sd weakly: the sd governs between-patient diversity in lesion "
             "type, which a pooled share barely constrains. It is taken from the fit here, and is the parameter to revisit when "
             "per-participant error mixes with more than 15 items each are available.",
             "\nWhat the prior can and cannot fix: it trades word errors for nonwords, so it sets the nonword share. The remaining "
             "excess of formal and unrelated errors relative to semantic ones is fixed by the SP model's six-word neighbourhood "
             "(two formal and two unrelated competitors against one semantic) and does not move with the prior.",
             "\nThese expected-probability shares ignore item difficulty and realizer fallbacks; `results/engine_validation.md` "
             "table 2c is the full-simulation check on the held-out participants."]
    REPORT.write_text("\n".join(lines) + "\n")
    print("\n".join(lines))
    print(f"\nreport -> {REPORT}")


if __name__ == "__main__":
    main()
