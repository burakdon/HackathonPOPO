"""How close are the simulated patients to real people with aphasia?

Real data (data/PNT_SOURCE.md): naming-ability scores of 335 people with aphasia on the Philadelphia
Naming Test (T-scale), and the 175 PNT items' measured difficulties under the published 1PL model
p(correct) = sigmoid(0.182 * (theta - b_item)).

For each simulated patient we compute the expected uncued, unfatigued accuracy on all 175 items and
convert it to the theta that gives the same expected accuracy under the published model, so real
and simulated patients are compared on the same scale. Reported per cohort: median and 10-90%
range of theta, percentile of the cohort median among real patients, and for the training population
the Kolmogorov-Smirnov distance to the real distribution. Also: correlation between simulated and
model-predicted per-item accuracy (item order).

Writes results/pnt_calibration.md and results/pnt_calibration.png.
Usage:  uv run python -m scripts.calibrate_pnt [--config configs/sim_pnt.yaml]
"""
from __future__ import annotations

import argparse
import csv

import numpy as np

from core.config import load_clinical, resolve
from sim.config import load_sim
from sim.items import load_items
from sim.population import make_patients

SLOPE = 0.182


def theta_equivalent(acc: float, b: np.ndarray) -> float:
    lo, hi = -50.0, 150.0
    for _ in range(60):        # bisection: mean sigmoid is increasing in theta
        mid = 0.5 * (lo + hi)
        if np.mean(1 / (1 + np.exp(-SLOPE * (mid - b)))) < acc:
            lo = mid
        else:
            hi = mid
    return 0.5 * (lo + hi)


def ks(a: np.ndarray, b: np.ndarray) -> float:
    grid = np.sort(np.concatenate([a, b]))
    return float(np.max(np.abs(np.searchsorted(np.sort(a), grid, side="right") / len(a)
                               - np.searchsorted(np.sort(b), grid, side="right") / len(b))))


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--config", default="configs/sim_pnt.yaml")
    ap.add_argument("--n", type=int, default=335)
    args = ap.parse_args()
    cfg, clinical = load_sim(args.config), load_clinical()
    bank = load_items(cfg.items)
    b = np.array([float(r["irt_difficulty_t"]) for r in csv.DictReader(open(resolve("data/pnt_items.csv")))])
    real = np.array([float(r["theta_t"]) for r in csv.DictReader(open(resolve("data/pnt_thetas.csv")))])

    rows, sims, item_acc = [], {}, None
    for cohort in ["population", *cfg.presets]:
        th, accs = [], []
        for spec in make_patients(cfg, cohort, "test", args.n, 0):
            patient, _ = spec.build(bank, cfg, clinical)
            p = patient.retrieval_probabilities()
            accs.append(p)
            th.append(theta_equivalent(float(p.mean()), b))
        th = np.array(th)
        sims[cohort] = th
        if cohort == "population":
            item_acc = np.mean(accs, axis=0)
        rows.append({"cohort": cohort, "median": np.median(th), "p10": np.percentile(th, 10), "p90": np.percentile(th, 90),
                     "pct_real": 100 * np.mean(real <= np.median(th)), "ks": ks(th, real)})
    # Per-item: simulated population accuracy vs the published model's prediction averaged over real patients.
    pred = np.mean(1 / (1 + np.exp(-SLOPE * (real[:, None] - b[None, :]))), axis=0)
    r_items = float(np.corrcoef(item_acc, pred)[0, 1])

    lines = ["<!-- Generated by: uv run python -m scripts.calibrate_pnt. Do not edit by hand. -->",
             f"Simulated patients ({args.config}) vs {len(real)} real people with aphasia, on the Philadelphia "
             f"Naming Test ability scale (T-scale; real median {np.median(real):.1f}, 10-90% "
             f"{np.percentile(real, 10):.1f} to {np.percentile(real, 90):.1f}). {args.n} simulated patients per row.", "",
             "| simulated group | median theta | 10-90% range | cohort median = real patient percentile | KS distance to real |",
             "|---|---|---|---|---|"]
    for r in rows:
        lines.append(f"| {r['cohort']} | {r['median']:.1f} | {r['p10']:.1f} to {r['p90']:.1f} | {r['pct_real']:.0f}th | "
                     f"{r['ks']:.2f}{' (training population)' if r['cohort'] == 'population' else ''} |")
    lines += ["", f"Per item: simulated population accuracy vs the published model's prediction for the real patients, "
              f"correlation r = {r_items:.2f} over 175 items.", "",
              "KS distance: 0 = identical distributions, 1 = no overlap. Only the training population is drawn from "
              "real scores; the named cohorts are deliberately narrow profiles, so their KS distance is large by design."]
    resolve("results/pnt_calibration.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[1:]))

    import matplotlib
    matplotlib.use("Agg")
    import matplotlib.pyplot as plt
    fig, axes = plt.subplots(1, 2, figsize=(11, 3.8))
    bins = np.linspace(15, 80, 27)
    axes[0].hist(real, bins=bins, density=True, alpha=0.55, label=f"real patients (n={len(real)})", color="#555")
    axes[0].hist(sims["population"], bins=bins, density=True, histtype="step", lw=2,
                 label="simulated training population", color="#1f77b4")
    for c, col in zip(cfg.presets, ["#2ca02c", "#d62728", "#9467bd", "#ff7f0e"]):
        axes[0].axvline(np.median(sims[c]), color=col, ls="--", lw=1.2, label=f"{c} (median)")
    axes[0].set_xlabel("Philadelphia Naming Test ability (T-score)")
    axes[0].set_title("Naming ability: simulated vs real people with aphasia", fontsize=9)
    axes[0].legend(fontsize=7)
    axes[1].scatter(pred, item_acc, s=10)
    axes[1].plot([0, 1], [0, 1], color="#999", lw=1)
    axes[1].set_xlabel("predicted from real patients (published model)")
    axes[1].set_ylabel("simulated population")
    axes[1].set_title(f"Accuracy per PNT item (175 items), r = {r_items:.2f}", fontsize=9)
    fig.tight_layout()
    fig.savefig(resolve("results/pnt_calibration.png"), dpi=150)


if __name__ == "__main__":
    main()
