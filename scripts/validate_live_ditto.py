"""Fresh validation of POST /learn_from_overrides settings on states NOT used to choose them.

The live-DITTO settings (configs/service.yaml, live_ditto) were chosen on override states from
validation patients 100+ of the moderate cohort. Here, for each PPO model and 5 independent
repetitions: 10 override states ("after a sound error -> first_sound", clinician keeps the agent's
tier) come from fresh validation patients (1000 + 100*r ...), and the before/after evaluation uses
states from other fresh validation patients (2000+), in two cohorts. Writes
results/live_ditto_validation.md.

Usage:  uv run python -m scripts.validate_live_ditto
"""
from __future__ import annotations

import numpy as np
from sb3_contrib import MaskablePPO

from agents.ditto import action_probs
from core.config import load_clinical, load_service, resolve
from core.masks import ACTION_CUES
from core.schema import Action, State
from envs.aphasia_env import AphasiaEnv, load_env_config
from service.live_ditto import LiveDitto, state_type

MODELS = {"PPO, proxy reward (live agent)": "models/ppo_seed0.zip",
          "PPO, simulation objective": "models/ppo_privileged_seed0.zip"}
COHORTS = ["moderate_broca", "population"]
REPS, N_OVERRIDES = 5, 10


def collect(model, cohort: str, start: int, want_sound: int | None, max_patients: int = 60) -> list[State]:
    """Decision states visited by the model; if want_sound, only states right after a sound error."""
    env, out = AphasiaEnv(cohort=cohort, split="val"), []
    for k in range(start, start + max_patients):
        obs, _ = env.reset(options={"patient_index": k})
        done = False
        while not done:
            st = env._state()
            is_sound = bool(st.last_trials) and st.last_trials[-1].error_type == "sound"
            if want_sound is None or is_sound:
                out.append(st)
            a, _ = model.predict(obs, action_masks=env.action_masks(), deterministic=True)
            obs, _, done, _, _ = env.step(int(a))
        if want_sound is not None and len(out) >= want_sound:
            return out[:want_sound]
    return out


def main() -> None:
    clinical, env_cfg, scfg = load_clinical(), load_env_config(), load_service()
    lines = ["<!-- Generated by: uv run python -m scripts.validate_live_ditto. Do not edit by hand. -->",
             f"Fresh validation of POST /learn_from_overrides: {N_OVERRIDES} overrides 'after a sound error -> "
             f"first_sound' per repetition, {REPS} repetitions with different override patients; evaluation on "
             "states from other validation patients not used to choose the settings. Mean ± SD over repetitions.", "",
             "| model | cohort | held-out sound-error states | P(first_sound) before -> after | top action = first_sound "
             "before -> after | other state types: top action unchanged | seconds |", "|---|---|---|---|---|---|---|"]
    for label, path in MODELS.items():
        base = MaskablePPO.load(str(resolve(path)), device="cpu")
        live = LiveDitto(base, clinical, env_cfg, scfg.live_ditto)
        live.pool()
        for cohort in COHORTS:
            evals = collect(base, cohort, 2000, None, max_patients=40)
            ev_sound = [s for s in evals if s.last_trials and s.last_trials[-1].error_type == "sound"]
            ev_other = [s for s in evals if state_type(s.last_trials[-1].error_type if s.last_trials else None)
                        != "after a sound error"]
            enc = lambda states: tuple(np.stack(x) for x in zip(*[live.encode(s) for s in states]))
            so, sm = enc(ev_sound)
            oo, om = enc(ev_other)
            is_cue = np.array(ACTION_CUES) == "first_sound"
            p0 = action_probs(base, so, sm)
            res = []
            for r in range(REPS):
                ov_states = collect(base, cohort, 1000 + 100 * r, N_OVERRIDES)
                ovs = []
                for s in ov_states:
                    o, m = live.encode(s)
                    tier = int(np.argmax(action_probs(base, o[None], m[None])[0])) // 5 + 1
                    ovs.append((s, Action(tier=tier, cue="first_sound")))
                tuned, rep = live.learn(ovs, [])
                p1 = action_probs(tuned, so, sm)
                res.append({"pb": p0[:, is_cue].sum(1).mean(), "pa": p1[:, is_cue].sum(1).mean(),
                            "tb": np.mean(is_cue[p0.argmax(1)]), "ta": np.mean(is_cue[p1.argmax(1)]),
                            "un": np.mean(action_probs(base, oo, om).argmax(1) == action_probs(tuned, oo, om).argmax(1)),
                            "s": rep["seconds"]})
            f = lambda k: f"{np.mean([x[k] for x in res]):.2f} ± {np.std([x[k] for x in res]):.2f}"
            lines.append(f"| {label} | {cohort} | {len(ev_sound)} | {np.mean([x['pb'] for x in res]):.2f} -> {f('pa')} | "
                         f"{np.mean([x['tb'] for x in res]):.2f} -> {f('ta')} | {f('un')} (n={len(ev_other)}) | {f('s')} |")
            print(lines[-1], flush=True)
    resolve("results/live_ditto_validation.md").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
