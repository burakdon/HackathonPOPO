"""The named demo patients (docs/PERSONAS.md): their profile, and what each policy does with them.

For Maria and James (configs/sim_pnt.yaml presets demo_maria / demo_james) this prints:
  - naming ability on the real PNT scale and its percentile among 335 real people with aphasia;
  - error profile (share of meaning / sound / no-response errors) and which cue helps most;
  - 50 simulated sessions each (same patient, different days) with fixed difficulty and with the
    data-grounded PPO agent: time in band, quit rate, learning gain, and the cue the agent gives
    after each error type.
Writes results/demo_patients.md.
Usage:  uv run python -m scripts.demo_patients
"""
from __future__ import annotations

import collections
import csv

import numpy as np

from agents.baselines import FixedPolicy
from agents.ppo import PPOPolicy
from core.config import load_clinical, resolve
from envs.aphasia_env import load_env_config
from eval.metrics import session_metrics
from scripts.calibrate_pnt import theta_equivalent
from sim.config import load_sim
from sim.items import load_items
from sim.population import make_patients
from sim.session import run_session

PATIENTS = {"demo_maria": "Maria (sound errors)", "demo_james": "James (meaning errors)"}
CUES = ("first_sound", "first_letter", "semantic", "sentence_frame")


def main() -> None:
    cfg, clinical = load_sim("configs/sim_pnt.yaml"), load_clinical()
    bank = load_items(cfg.items)
    b = np.array([float(r["irt_difficulty_t"]) for r in csv.DictReader(open(resolve("data/pnt_items.csv")))])
    real = np.array([float(r["theta_t"]) for r in csv.DictReader(open(resolve("data/pnt_thetas.csv")))])
    ppo = PPOPolicy("models/ppo_pnt_seed0.zip", clinical, load_env_config())
    lines = ["<!-- Generated by: uv run python -m scripts.demo_patients. Do not edit by hand. -->",
             "Named demo patients (composites, see docs/PERSONAS.md) in the data-grounded simulator. "
             "50 simulated sessions per policy (same patient, different days).", ""]
    for key, label in PATIENTS.items():
        specs = make_patients(cfg, key, "test", 50, 0)
        p0, _ = specs[0].build(bank, cfg, clinical)
        theta = theta_equivalent(float(p0.retrieval_probabilities().mean()), b)
        err = np.zeros(3)
        for i in range(len(bank)):
            d = p0.error_distribution(i, "none")
            err += [d["meaning"], d["sound"], d["no_response"]]
        err /= err.sum()
        gains = {c: np.mean([p0.p_correct(i, c) - p0.p_correct(i, "none") for i in bank.indices_in_tier(2)]) for c in CUES}
        best = max(gains, key=gains.get)
        lines += [f"**{label}**", "",
                  f"- PNT ability {theta:.1f} (T-scale), {100 * np.mean(real <= theta):.0f}th percentile of 335 real people with aphasia",
                  f"- Errors: meaning {err[0]:.0%}, sound {err[1]:.0%}, no response {err[2]:.0%}",
                  "- Gain in p(correct) on tier-2 items from each cue: " + ", ".join(f"{c} +{g:.2f}" for c, g in gains.items())
                  + f" (best: {best})", "",
                  "| policy | in band | quit | learning gain x100 | cue after a sound error | cue after a meaning error |",
                  "|---|---|---|---|---|---|"]
        for name, make in (("fixed (tier 2)", lambda: FixedPolicy(tier=2)), ("our agent (PPO)", lambda: ppo)):
            rows, after = [], collections.defaultdict(collections.Counter)
            for spec in specs:
                patient, selector = spec.build(bank, cfg, clinical)
                res = run_session(make(), patient, selector, cfg, clinical)
                rows.append(session_metrics(res, clinical))
                tr = [t for t in res.trace if not t.get("probe")]
                for prev, cur in zip(res.trace, res.trace[1:]):
                    if not cur.get("probe") and prev["error_type"] in ("sound", "meaning"):
                        after[prev["error_type"]][cur["cue"]] += 1
            top = lambda e: (lambda c: f"{c.most_common(1)[0][0]} ({c.most_common(1)[0][1] / sum(c.values()):.0%})"
                             if c else "-")(after[e])
            lines.append(f"| {name} | {np.mean([r['time_in_band'] for r in rows]):.2f} | {np.mean([r['quit'] for r in rows]):.2f} | "
                         f"{100 * np.mean([r['learning_gain'] for r in rows]):.2f} | {top('sound')} | {top('meaning')} |")
        lines.append("")
    resolve("results/demo_patients.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[1:]))


if __name__ == "__main__":
    main()
