"""Does the agent read the error? Which cue a policy gives after each error type.

A speech therapist matches the cue to the error: after a sound error ("cap" for "cat") a
phonological cue (first sound / first letter); after a meaning error ("dog" for "cat") a cue that
feeds word selection (semantic / sentence frame). For each (policy, patient model) pair this
script runs the deterministic policy on held-out validation patients and tabulates the cue it
chooses after each error type.

"matched" = share of cue choices after an error that target the step that failed:
  after a sound error   -> first_sound or first_letter
  after a meaning error -> semantic or sentence_frame

Writes results/error_cue_table.md.
Usage:  uv run python -m scripts.error_cue_table
"""
from __future__ import annotations

import collections

import numpy as np
from sb3_contrib import MaskablePPO

from agents.ditto import action_probs
from core.config import resolve
from core.masks import ACTION_CUES
from envs.aphasia_env import AphasiaEnv
from sim.config import load_sim
from train.ditto_ppo import collect_states

PHON, SEM = {"first_sound", "first_letter"}, {"semantic", "sentence_frame"}
RUNS = [  # (label, model, simulator the patients come from)
    ("PPO trained on the original model, original patients", "models/ppo_seed0.zip", "configs/sim.yaml"),
    ("PPO trained on the original model, two-step patients", "models/ppo_seed0.zip", "configs/sim_two_step.yaml"),
    ("PPO trained on the two-step model, two-step patients", "models/ppo_two_step_seed0.zip", "configs/sim_two_step.yaml"),
    ("PPO trained on the original model, data-grounded patients", "models/ppo_seed0.zip", "configs/sim_pnt.yaml"),
    ("PPO trained on the data-grounded model, data-grounded patients", "models/ppo_pnt_seed0.zip", "configs/sim_pnt.yaml"),
]
CUES = ("first_sound", "first_letter", "semantic", "sentence_frame", "none")


def table(model_path: str, sim_path: str, patients: range) -> dict:
    model = MaskablePPO.load(str(resolve(model_path)), device="cpu")
    env = AphasiaEnv(cohort="population", split="val", sim_cfg=load_sim(sim_path))
    counts: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    for s in collect_states(model, env, patients):
        if s["last_error"] in ("sound", "meaning", "no_response"):
            a = int(action_probs(model, s["obs"][None], s["mask"][None])[0].argmax())
            counts[s["last_error"]][ACTION_CUES[a]] += 1
    out = {}
    for err, c in counts.items():
        n = sum(c.values())
        out[err] = {"n": n, **{q: c[q] / n for q in CUES}}
    matched = sum(counts["sound"][q] for q in PHON) + sum(counts["meaning"][q] for q in SEM)
    total = sum(counts["sound"].values()) + sum(counts["meaning"].values())
    out["matched"] = matched / total if total else float("nan")
    return out


def main() -> None:
    patients = range(100, 200)
    lines = ["<!-- Generated by: uv run python -m scripts.error_cue_table. Do not edit by hand. -->",
             "Cue chosen by the deterministic policy after each error type, on 100 held-out validation patients "
             "(broad population). **Matched** = after a sound error a phonological cue (first sound/letter), after a "
             "meaning error a cue that feeds word selection (semantic/sentence frame).", ""]
    for label, model, sim in RUNS:
        if not resolve(model).exists():
            lines += [f"**{label}**: model {model} not found, skipped.", ""]
            continue
        t = table(model, sim, patients)
        lines += [f"**{label}** (matched {t['matched']:.0%})", "",
                  "| after a... | n | " + " | ".join(CUES) + " |", "|---" * (len(CUES) + 2) + "|"]
        for err in ("sound", "meaning", "no_response"):
            if err in t:
                lines.append(f"| {err} error | {t[err]['n']} | " + " | ".join(f"{t[err][q]:.0%}" for q in CUES) + " |")
        lines.append("")
        print(label, f"matched {t['matched']:.2f}", flush=True)
    resolve("results/error_cue_table.md").write_text("\n".join(lines) + "\n")
    print("\n".join(lines[1:]))


if __name__ == "__main__":
    main()
