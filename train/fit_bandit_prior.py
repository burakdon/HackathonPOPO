"""Fit an empirical-Bayes prior for the contextual logistic bandit from simulated TRAINING patients.

This is the bandit's sim-to-real pretraining. Instead of a hand-set prior, the bandit starts from
what the simulated population says about how p(correct) depends on tier, cue and context, and,
crucially, how much that varies between patients:

1. For each training patient, play several sessions with a uniform-random exploration policy
   (every allowed action equally likely), so the data covers all tier x cue x context combinations.
2. Fit a per-patient MAP logistic regression (Newton's method), regularised toward the hand-set
   prior so patients with little signal stay sensible.
3. Prior mean = mean of the per-patient weights; prior covariance = their covariance, shrunk toward
   its diagonal and inflated (configs/bandit_prior.yaml).

Trade-off: the prior inherits every simulator assumption. Inflation keeps it humble so a real
person's data overrides it within a few dozen trials (tested in tests/test_bandit_prior.py).
Evaluation cohorts (test split) are never touched.

Usage:  uv run python -m train.fit_bandit_prior
"""
from __future__ import annotations

from datetime import datetime, timezone

import numpy as np
import yaml

from agents.logistic_bandit import FEATURES, N_FEATURES, LogisticThompsonBandit
from core.config import load_clinical, load_logistic_bandit, load_yaml, resolve
from core.masks import ACTION_CUES, ACTION_TIERS, action_index
from core.schema import Action, Outcome, State
from sim.config import load_sim
from sim.items import ItemSelector, load_items
from sim.patient import SimPatient
from sim.population import make_patients
from sim.session import run_session


class RandomRecorder:
    """Uniform-random exploration policy that records (features of chosen action, outcome)."""

    name = "random_recorder"

    def __init__(self, featurizer: LogisticThompsonBandit, rng: np.random.Generator) -> None:
        self.featurizer, self.rng = featurizer, rng
        self.X: list[np.ndarray] = []
        self.y: list[float] = []

    def act(self, state: State, mask: np.ndarray) -> Action:
        i = int(self.rng.choice(np.flatnonzero(mask)))
        return Action(tier=int(ACTION_TIERS[i]), cue=ACTION_CUES[i])

    def update(self, state: State, action: Action, outcome: Outcome) -> None:
        self.X.append(self.featurizer.features(state)[action_index(action.tier, action.cue)])
        self.y.append(float(outcome.correct))


def map_logistic(X: np.ndarray, y: np.ndarray, m0: np.ndarray, S0_inv: np.ndarray, iters: int) -> np.ndarray:
    """MAP weights under prior N(m0, S0) by Newton's method (the objective is strictly convex)."""
    w = m0.copy()
    for _ in range(iters):
        p = 1.0 / (1.0 + np.exp(-(X @ w)))
        grad = X.T @ (p - y) + S0_inv @ (w - m0)
        H = (X * (p * (1 - p))[:, None]).T @ X + S0_inv
        step = np.linalg.solve(H, grad)
        w -= step
        if np.max(np.abs(step)) < 1e-6:
            break
    return w


def main() -> None:
    fit = load_yaml("configs/bandit_prior.yaml")
    cfg, clinical = load_sim(), load_clinical()
    bank = load_items(cfg.items)
    # Featurize with the hand-set prior config (features do not depend on the prior itself).
    hand = load_logistic_bandit().model_copy(update={"prior_file": None})
    featurizer = LogisticThompsonBandit(hand, clinical, seed=0)
    m0, S0_inv = featurizer.mu.copy(), np.linalg.inv(featurizer.Sigma)

    W = []
    n_obs = 0
    for spec in make_patients(cfg, "population", "train", fit["n_patients"], root_seed=fit["seed"]):
        rec = RandomRecorder(featurizer, np.random.default_rng([fit["seed"], spec.index, 0]))
        for s in range(fit["sessions_per_patient"]):
            ss = np.random.SeedSequence([fit["seed"], spec.index, s + 1])
            o_ss, sel_ss = ss.spawn(2)
            patient = SimPatient(spec.params, bank, cfg, clinical, np.random.default_rng(o_ss))
            run_session(rec, patient, ItemSelector(bank, np.random.default_rng(sel_ss)), cfg, clinical,
                        n_trials=fit["trials_per_session"])
        X, y = np.array(rec.X), np.array(rec.y)
        n_obs += len(y)
        W.append(map_logistic(X, y, m0, S0_inv, fit["newton_iterations"]))
    W = np.array(W)

    mean = W.mean(axis=0)
    cov = np.cov(W, rowvar=False)
    lam, infl = fit["shrinkage"], fit["inflation"]
    Sigma = infl * ((1 - lam) * cov + lam * np.diag(np.diag(cov)))
    Sigma[np.diag_indices(N_FEATURES)] = np.maximum(np.diag(Sigma), fit["min_variance"])
    np.linalg.cholesky(Sigma)  # fail loudly if not positive definite

    out = {
        "_comment": "GENERATED by train/fit_bandit_prior.py from the TRAINING population. Do not edit by hand.",
        "generated_utc": datetime.now(timezone.utc).isoformat(timespec="seconds"),
        "fit_config": {k: fit[k] for k in fit if k != "output"},
        "n_patients": int(len(W)), "n_observations": int(n_obs),
        "features": FEATURES,
        "mean": [round(float(v), 5) for v in mean],
        "cov": [[round(float(v), 6) for v in row] for row in Sigma],
    }
    path = resolve(fit["output"])
    with open(path, "w") as f:
        yaml.safe_dump(out, f, sort_keys=False, width=200)
    print(f"fitted on {len(W)} training patients, {n_obs} trials -> {path}")
    print(f"{'feature':26} {'hand mean':>9} {'fit mean':>9} {'fit sd':>7}")
    for k, f_ in enumerate(FEATURES):
        print(f"{f_:26} {m0[k]:9.2f} {mean[k]:9.2f} {np.sqrt(Sigma[k, k]):7.2f}")


if __name__ == "__main__":
    main()
